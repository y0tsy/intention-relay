/// Writes every public DTO of this crate into the configured export directory.
///
/// The test is ignored by default: it mutates the working tree, and the two
/// Makefile targets that own that mutation are the only callers.
#[test]
#[ignore = "writes the committed bindings; run through `make bindings`"]
fn the_wire_types_export_to_the_terminal_app() {
    let config = Config::from_env();
    export(&config);

    // The barrel is generated too. A hand-maintained re-export list drifts the
    // moment a DTO is added, and the identifier newtypes are written as
    // dependencies of the types above rather than being exported themselves,
    // so the directory is the only complete source of names.
    let mut names = std::fs::read_dir(config.out_dir())
        .expect("the export directory exists")
        .map(|entry| {
            entry
                .expect("a readable export directory entry")
                .file_name()
        })
        .filter_map(|name| name.to_str().map(str::to_owned))
        .filter(|name| name.ends_with(".ts") && name != "index.ts")
        .map(|name| name.trim_end_matches(".ts").to_owned())
        .collect::<Vec<_>>();
    names.sort_unstable();

    let mut barrel = String::from(
        "// This file was generated by the intention-proto bindings test. Do not edit it manually.\n",
    );
    for name in names {
        barrel.push_str(&format!("export type * from \"./{name}\";\n"));
    }
    std::fs::write(config.out_dir().join("index.ts"), barrel)
        .expect("the export directory accepts the barrel");
}

