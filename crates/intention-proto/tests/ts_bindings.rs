//! Exports the TypeScript declarations the terminal app compiles against.
//!
//! The bindings are generated from the Rust wire types rather than written by
//! hand, so a change to a DTO reaches the terminal app as a compile error
//! instead of a silently mismatched decoder. `make bindings` writes the
